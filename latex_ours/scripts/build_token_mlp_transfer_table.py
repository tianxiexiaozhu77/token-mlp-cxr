#!/usr/bin/env python3
"""Export the fixed NIH-to-CheXpert transfer comparison from verified results."""
import csv
import hashlib
import json
import math
from pathlib import Path
import shutil
import statistics

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
RUN = ROOT / 'experiments/nih_chexpert_transfer/runs/20261121'
MODELS = ('AlphaRAD', 'RadZero')
METHODS = ('original', 'linear_probe', 'clip_global', 'post_mlp', 'pre_mlp')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(path):
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def main():
    completion = json.loads((RUN / 'COMPLETION.json').read_text())
    assert completion['status'] == 'complete' and completion['new_training_runs'] == 0
    for name, expected in completion['output_sha256'].items():
        assert digest(RUN / name) == expected, name
    verification = json.loads((RUN / 'FINAL_VERIFICATION.json').read_text())
    assert verification['status'] == 'passed'
    assert verification['completion_sha256'] == digest(RUN / 'COMPLETION.json')
    protocol = json.loads((RUN / 'PROTOCOL.json').read_text())
    assert protocol['models'] == list(MODELS) and protocol['methods'] == list(METHODS)
    assert protocol['seeds'] == [42, 43, 44]
    assert (protocol['images'], protocol['patients'], protocol['groups']) == (668, 500, 500)
    assert len(protocol['class_names']) == 7 and len(protocol['source_class_names']) == 14
    assert protocol['bootstrap']['resamples'] == 2000
    rows = read_csv(RUN / 'summary.csv')
    seeds = read_csv(RUN / 'per_seed_results.csv')
    assert len(rows) == 10 and len(seeds) == 26
    assert {(r['model'], r['method']) for r in rows} == {(m, t) for m in MODELS for t in METHODS}
    for row in rows:
        fitted = sorted((s for s in seeds if (s['model'], s['method']) == (row['model'], row['method'])),
                        key=lambda s: int(s['seed']))
        assert [int(s['seed']) for s in fitted] == ([42] if row['method'] == 'original' else [42, 43, 44])
        for metric in ('macro_auroc', 'macro_ap'):
            values = [float(s[metric]) for s in fitted]
            assert math.isclose(float(row[metric + '_mean']), statistics.mean(values), abs_tol=1e-12)
            sd = statistics.stdev(values) if len(values) > 1 else 0.
            assert math.isclose(float(row[metric + '_sd']), sd, abs_tol=1e-12)
    intervals = read_csv(RUN / 'uncertainty/macro_differences.csv')
    assert len(intervals) == 16
    for item in intervals:
        pre = next(r for r in rows if (r['model'], r['method']) == (item['model'], 'pre_mlp'))
        other = next(r for r in rows if (r['model'], r['method']) ==
                     (item['model'], item['comparison'].removeprefix('pre_mlp minus ')))
        key = 'macro_' + item['metric'] + '_mean'
        assert math.isclose(float(item['delta_pp']), 100*(float(pre[key])-float(other[key])), abs_tol=1e-10)
        assert int(item['valid_replicates']) == int(item['total_replicates']) == 2000
    lines = [
        '% Generated by scripts/build_token_mlp_transfer_table.py; do not hand-edit.',
        r'\begin{table*}[!t]', r'\centering', r'\small',
        r'\setlength{\tabcolsep}{4pt}', r'\renewcommand{\arraystretch}{1.15}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lccccc@{}}', r'\toprule',
        r'Model & Original & Linear probe & Global adapter$^{\dagger}$ & Post MLP & Pre MLP \\', r'\midrule',
    ]
    for model in MODELS:
        group = [next(r for r in rows if (r['model'], r['method']) == (model, method)) for method in METHODS]
        best = {key: max(float(r[key]) for r in group) for key in ('macro_auroc_mean', 'macro_ap_mean')}
        cells = []
        for row in group:
            pair = []
            for key in best:
                value = f'{100*float(row[key]):.2f}'
                pair.append(r'\mathbf{' + value + '}' if value == f'{100*best[key]:.2f}' else value)
            cells.append('$' + r'\,/\,'.join(pair) + '$')
        lines.append(' & '.join([model, *cells]) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular*}',
        r'\caption{ChestXray14 $\rightarrow$ CheXpert transfer on 668 images from 500 patients, retaining seven shared labels. Fitting and checkpoint selection use only the NIH training and validation partitions in Sec.~\ref{sec:large_patient_protocol}; CheXpert is used only for evaluation in this transfer experiment. Cells show macro AUROC / AP (\%); fitted methods report the mean over seeds 42/43/44, and Original is evaluated once. Bold marks the highest displayed value per metric, not statistical significance. This previously used CheXpert cohort is not a new blind cohort, and its seven-label scores are not directly comparable to the primary 12-label results. $^{\dagger}$The global adapter uses the CLS route described in Sec.~\ref{sec:supervised_baseline_protocol}.}',
        r'\label{tab:token_mlp_transfer}', r'\end{table*}', '']
    target = PAPER / 'tables/token_mlp_transfer.tex'
    target.write_text('\n'.join(lines))
    exported = {}
    for source, name in [('summary.csv', 'token_mlp_transfer.csv'),
                         ('per_seed_results.csv', 'token_mlp_transfer_per_seed.csv'),
                         ('uncertainty/macro_differences.csv', 'token_mlp_transfer_intervals.csv')]:
        path = PAPER / 'supplement_data' / name
        shutil.copyfile(RUN / source, path)
        exported[name] = digest(path)
    names = ('COMPLETION.json', 'FINAL_VERIFICATION.json', 'PROTOCOL.json', 'COHORT_AUDIT.json',
             'summary.csv', 'per_seed_results.csv', 'uncertainty/summary.json', 'uncertainty/macro_differences.csv')
    provenance = dict(status='verified', displayed_method_summaries=10, underlying_evaluations=26,
        additional_fits=0, paired_comparisons=8, source_run=str(RUN.relative_to(ROOT)),
        source_sha256={name: digest(RUN / name) for name in names},
        table_sha256=digest(target), csv_sha256=exported, exporter_sha256=digest(Path(__file__)))
    (PAPER / 'supplement_data/token_mlp_transfer_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Exported 2 rows; verified 10 summaries, 26 evaluations and 16 paired macro intervals.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Export the larger patient-disjoint ChestXray14 comparison from saved results."""
import csv
import hashlib
import json
import math
from pathlib import Path
import statistics

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
RUN = ROOT / 'experiments/large_patient_multilabel/runs/20261121'
MODELS = ('AlphaRAD', 'RadZero')
METHODS = ('original', 'linear_probe', 'clip_global', 'post_mlp', 'pre_mlp')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_csv(path):
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def main():
    completion = json.loads((RUN / 'COMPLETION.json').read_text())
    assert completion['status'] == 'complete'
    for name, expected in completion['output_sha256'].items():
        assert digest(RUN / name) == expected, name
    verification = json.loads((RUN / 'FINAL_VERIFICATION.json').read_text())
    assert verification['status'] == 'passed'
    assert verification['completion_sha256'] == digest(RUN / 'COMPLETION.json')
    protocol = json.loads((RUN / 'PROTOCOL.json').read_text())
    assert protocol['models'] == list(MODELS) and protocol['seeds'] == [42, 43, 44]
    assert len(protocol['class_names']) == 14
    assert protocol['split_stats']['test']['images'] == 6727
    assert protocol['split_stats']['test']['patients'] == 1856
    rows = [r for r in read_csv(RUN / 'summary.csv') if r['method'] in METHODS]
    seeds = [r for r in read_csv(RUN / 'per_seed_results.csv') if r['method'] in METHODS]
    assert len(rows) == 10 and len(seeds) == 26
    for row in rows:
        fitted = sorted((s for s in seeds if (s['model'], s['method']) == (row['model'], row['method'])),
                        key=lambda s: int(s['seed']))
        assert [int(s['seed']) for s in fitted] == ([42] if row['method'] == 'original' else [42, 43, 44])
        for metric in ('auroc', 'ap'):
            values = [float(s[metric + '_pct']) for s in fitted]
            assert math.isclose(float(row[metric + '_mean_pct']), statistics.mean(values), abs_tol=1e-8)
            if len(values) > 1:
                assert math.isclose(float(row[metric + '_sd_pct']), statistics.stdev(values), abs_tol=1e-8)
    lines = [
        '% Generated by scripts/build_token_mlp_large_patient_table.py; do not hand-edit.',
        r'\begin{table*}[!t]', r'\centering', r'\small',
        r'\setlength{\tabcolsep}{4pt}', r'\renewcommand{\arraystretch}{1.15}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}lccccc@{}}', r'\toprule',
        r'Model & Original & Linear probe & Global adapter$^{\dagger}$ & Post MLP & Pre MLP \\', r'\midrule',
    ]
    for model in MODELS:
        group = [next(r for r in rows if (r['model'], r['method']) == (model, m)) for m in METHODS]
        best = {k: max(float(r[k]) for r in group) for k in ('auroc_mean_pct', 'ap_mean_pct')}
        cells = []
        for row in group:
            pair = []
            for key in best:
                value = f"{float(row[key]):.2f}"
                pair.append(r'\mathbf{' + value + '}' if value == f'{best[key]:.2f}' else value)
            cells.append('$' + r'\,/\,'.join(pair) + '$')
        lines.append(' & '.join([model, *cells]) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular*}',
        r'\caption{Larger patient-disjoint ChestXray14 evaluation: 6,727 test images from 1,856 patients, retaining all 14 labels. Training/validation contain 13,406/2,300 images from 3,712/619 patients. Cells show macro AUROC / AP (\%); fitted methods report the mean over seeds 42/43/44, and Original is evaluated once. Bold marks the highest displayed value per metric, not statistical significance. All fitted methods are trained afresh on the new split. This is a repartition of the previously used local NIH cohort, not an official benchmark split or a new blind external cohort. $^{\dagger}$The global adapter uses the CLS route described in Sec.~\ref{sec:supervised_baseline_protocol}.}',
        r'\label{tab:token_mlp_large_patient}', r'\end{table*}', '']
    target = PAPER / 'tables/token_mlp_large_patient.tex'
    target.write_text('\n'.join(lines))
    data = PAPER / 'supplement_data/token_mlp_large_patient.csv'
    with data.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    names = ('COMPLETION.json', 'FINAL_VERIFICATION.json', 'PROTOCOL.json', 'SPLIT_AUDIT.json',
             'SELECTION_LOCK.json', 'summary.csv', 'per_seed_results.csv', 'uncertainty/summary.json')
    provenance = dict(status='verified', displayed_method_summaries=10, underlying_evaluations=26,
        additional_fits=24, source_run=str(RUN.relative_to(ROOT)),
        source_sha256={name: digest(RUN / name) for name in names},
        table_sha256=digest(target), csv_sha256=digest(data), exporter_sha256=digest(Path(__file__)))
    (PAPER / 'supplement_data/token_mlp_large_patient_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Exported 2 table rows; verified 10 method summaries against 26 saved evaluations.')


if __name__ == '__main__':
    main()

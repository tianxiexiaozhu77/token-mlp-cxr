#!/usr/bin/env python3
"""Export completed MaCo pooling, Both, and gate/loss experiments into the paper.

Validate reported means/SDs against every exported seed before writing tables.
This checks saved reporting artifacts, not model inference or test predictions.
No training is launched and no checkpoint is selected by this script.
"""
import csv
import hashlib
import json
import math
from pathlib import Path
import shutil
import statistics

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
MODELS = ('AlphaRAD', 'RadZero', 'CARZero', 'KAD', 'BiomedCLIP', 'BioViL-T', 'MaCo')
DATASETS = {'openi': 'OpenI', 'chexpert': 'CheXpert', 'chestxray14': 'ChestXray14'}
CAMPAIGNS = {
    'placement': ROOT / 'experiments/adapter_placement_classification/runs/20261119',
    'both': ROOT / 'experiments/both_adapter_classification/runs/20261119',
    'gated_asl': ROOT / 'experiments/gated_asl_classification/runs/20261120_recovered',
}
METRICS = ('macro_auroc', 'macro_auprc')


def read_csv(path):
    with path.open(newline='') as handle:
        return list(csv.DictReader(handle))


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def check_equal(actual, expected, context):
    if not math.isclose(float(actual), float(expected), rel_tol=1e-10, abs_tol=1e-8):
        raise ValueError(f'{context}: {actual} != {expected}')


def group(rows, model, dataset, method):
    return sorted((r for r in rows if (r['model'], r['dataset'], r['method']) ==
                   (model, dataset, method)), key=lambda r: int(r['seed']))


def check_group(row, seed_rows, method, prefix):
    runs = group(seed_rows, row['model'], row['dataset'], method)
    if not runs:
        raise ValueError(f'Missing runs: {row["model"]}/{row["dataset"]}/{method}')
    deterministic = method in ('original', 'aggregation_only')
    if [int(r['seed']) for r in runs] != ([42] if deterministic else [42, 43, 44]):
        raise ValueError(f'Unexpected seeds: {runs}')
    for metric in METRICS:
        values = [float(r[metric + '_pct']) for r in runs]
        check_equal(row[prefix + metric + '_mean_pct'], statistics.mean(values), method)
        if not deterministic:
            check_equal(row[prefix + metric + '_sd_pct'], statistics.stdev(values), method)
    return runs


def pair(row, prefix):
    values = []
    for metric in METRICS:
        mean = float(row[prefix + metric + '_mean_pct'])
        sd = row.get(prefix + metric + '_sd_pct', '')
        values.append(f'{mean:.2f}' + (rf'\!\pm\!{float(sd):.2f}' if sd else ''))
    return '$' + r'\,/\,'.join(values) + '$'


def write_table(name, columns, header, rows, caption, label, star=True):
    environment = 'table*' if star else 'table'
    content = [
        '% Generated by scripts/build_token_mlp_ablation_tables.py; do not hand-edit.',
        rf'\begin{{{environment}}}[!htbp]', r'\centering', r'\footnotesize',
        r'\setlength{\tabcolsep}{4pt}', r'\renewcommand{\arraystretch}{1.12}',
        r'\resizebox{\textwidth}{!}{%', rf'\begin{{tabular}}{{@{{}}{columns}@{{}}}}',
        r'\toprule', header + r' \\', r'\midrule',
    ]
    for row in rows:
        content.append(r'\midrule' if row is None else ' & '.join(row) + r' \\')
    content += [r'\bottomrule', r'\end{tabular}}', rf'\caption{{{caption}}}',
                rf'\label{{{label}}}', rf'\end{{{environment}}}', '']
    target = PAPER / 'tables' / (name + '.tex')
    target.write_text('\n'.join(content))
    return target


def main():
    main_provenance = json.loads((PAPER / 'supplement_data/token_mlp_results_provenance.json').read_text())
    provenance = {'scope': 'Validate exported per-seed arithmetic and protocol identity; no inference replay.',
                  'generator_sha256': digest(Path(__file__)), 'campaigns': {}, 'tables': {}}
    summaries, seed_exports = {}, {}
    sources = {str(Path(r['result_path']).parent) for r in main_provenance['runs']
               if r['method'] == 'token_mlp'}
    for campaign, directory in CAMPAIGNS.items():
        protocol = json.loads((directory / 'PROTOCOL.json').read_text())
        audit = json.loads((directory / 'AUDIT.json').read_text())
        if audit['status'] != 'passed' or audit.get('errors'):
            raise ValueError(f'Campaign audit not passed: {directory}')
        for dataset, spec in protocol['datasets'].items():
            for field in ('sha256', 'samples_sha256'):
                if spec[field] != main_provenance['datasets'][dataset][field]:
                    raise ValueError(f'Dataset mismatch: {campaign}/{dataset}/{field}')
        rows = read_csv(directory / 'summary.csv')
        seeds = read_csv(directory / 'per_seed.csv')
        if len(rows) != (12 if campaign == 'placement' else 21):
            raise ValueError(f'Incomplete summary: {campaign}')
        if len(seeds) != {'placement': 72, 'both': 183, 'gated_asl': 252}[campaign]:
            raise ValueError(f'Incomplete seed export: {campaign}')
        keys = [(r['model'], r['dataset'], r['method'], r['seed']) for r in seeds]
        if len(keys) != len(set(keys)):
            raise ValueError(f'Duplicate seed records: {campaign}')
        for row in rows:
            if campaign == 'placement':
                pre = check_group(row, seeds, row['pre_method'], 'pre_')
                post = check_group(row, seeds, row['post_method'], 'post_')
                for metric in METRICS:
                    delta = [float(a[metric + '_pct']) - float(b[metric + '_pct'])
                             for a, b in zip(pre, post)]
                    check_equal(row['pre_minus_post_' + metric + '_mean_pp'], statistics.mean(delta), 'delta')
                    check_equal(row['pre_minus_post_' + metric + '_sd_pp'], statistics.stdev(delta), 'delta SD')
            else:
                methods = ('original', 'pre_mlp', 'post_mlp', 'both_mlp') if campaign == 'both' else (
                    'pre_bce', 'gated_bce', 'pre_asl', 'gated_asl')
                for method in methods:
                    if row[method + '_status'] == 'unavailable' and method == 'post_mlp':
                        if group(seeds, row['model'], row['dataset'], method):
                            raise ValueError('Unavailable method has seed records')
                        continue
                    if row[method + '_status'] != 'complete':
                        raise ValueError('Incomplete cell')
                    check_group(row, seeds, method, method + '_')
        for r in seeds:
            if r['method'] not in ('original', 'aggregation_only'):
                sources.add(r['source'])
        summaries[campaign], seed_exports[campaign] = rows, seeds
        records = {}
        for filename in ('summary.csv', 'per_seed.csv', 'PROTOCOL.json', 'AUDIT.json'):
            source = directory / filename
            records[filename] = {'path': str(source), 'sha256': digest(source)}
            if filename.endswith('.csv'):
                shutil.copyfile(source, PAPER / 'supplement_data' / f'token_mlp_{campaign}_{filename}')
        provenance['campaigns'][campaign] = {'sources': records, 'seed_records': len(seeds),
            'additional_fits': protocol['new_training_runs'], 'source_audit_status': audit['status'],
            'epoch_zero_counts': {m: sum(r['method'] == m and int(r['best_epoch']) == 0 for r in seeds)
                                  for m in sorted(set(r['method'] for r in seeds))}}

    tables = []
    placement = summaries['placement']
    rows = []
    for dataset, display in DATASETS.items():
        native = next(r for r in placement if r['model'] == 'MaCo' and r['dataset'] == dataset and r['pooling'] == 'native_mean')
        guided = next(r for r in placement if r['model'] == 'MaCo' and r['dataset'] == dataset and r['pooling'] == 'text_guided')
        rows.append([display, pair(native, 'pre_'), pair(native, 'post_'), pair(guided, 'pre_'), pair(guided, 'post_')])
    tables.append(write_table('token_mlp_pooling_placement', 'lcccc',
        'Dataset & Mean: Pre & Mean: Post & Text-guided: Pre & Text-guided: Post', rows,
        r'MaCo pooling $\times$ placement. Cells show macro AUROC / AP (\%), mean $\pm$ sample SD over three seeds. All four conditions fit one shared 99,136-parameter MLP with the same training protocol; pooling has no trainable parameters. Native mean pooling contributes 18 fits. Frozen pooling controls appear in Table~\ref{tab:token_mlp_aggregation_control}.',
        'tab:token_mlp_pooling_placement'))
    for dataset, display in DATASETS.items():
        rows = []
        for model in MODELS:
            row = next(r for r in summaries['both'] if (r['model'], r['dataset']) == (model, dataset))
            rows.append([model] + [r'\textemdash' if row[m + '_status'] == 'unavailable' else pair(row, m + '_')
                                  for m in ('original', 'pre_mlp', 'post_mlp', 'both_mlp')])
        tables.append(write_table('token_mlp_both_' + dataset, 'lcccc',
            'Model & Original & Pre MLP & Post MLP & Both MLP', rows,
            rf'Joint adaptation on {display}. Cells show macro AUROC / AP (\%); fitted conditions report three-seed mean $\pm$ sample SD. Original is deterministic. Both trains two independent MLPs, doubling the single-position parameter count; Pre and available Post results are reused. Dashes mark unrun Post conditions. Identity adapters in the three added-pooling models recover aggregation-only, not Original.',
            'tab:token_mlp_both_' + dataset, star=False))
        rows = []
        for model in MODELS:
            row = next(r for r in summaries['gated_asl'] if (r['model'], r['dataset']) == (model, dataset))
            rows.append([model] + [pair(row, m + '_') for m in ('pre_bce', 'gated_bce', 'pre_asl', 'gated_asl')])
        tables.append(write_table('token_mlp_gated_asl_' + dataset, 'lcccc',
            'Model & Pre + BCE & Gated + BCE & Pre + ASL & Gated + ASL', rows,
            rf'Gating $\times$ loss on {display}. All four conditions are newly trained within this experiment, including the ungated BCE control. Cells show macro AUROC / AP (\%), mean $\pm$ sample SD over seeds 42/43/44. BCE uses training-derived positive-class weights; ASL does not. Gating adds $d+1$ parameters. Checkpoints maximize validation AUROC with epoch zero eligible. Historical Pre results are not substituted for the fresh control.',
            'tab:token_mlp_gated_asl_' + dataset, star=False))
    if len(sources) != 423:
        raise ValueError(f'Unexpected unique fit count: {len(sources)}')
    provenance['unique_supervised_fits_including_main_study'] = len(sources)
    provenance['additional_fits'] = sum(v['additional_fits'] for v in provenance['campaigns'].values())
    for table in tables:
        provenance['tables'][str(table.relative_to(PAPER))] = digest(table)
    (PAPER / 'supplement_data/token_mlp_ablation_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print(f'Validated seed arithmetic and dataset hashes; exported {len(tables)} tables, {len(sources)} unique fits including the main study.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Export the requested AlphaRAD/RadZero comparison from audited saved results."""
import csv
import hashlib
import json
import math
from pathlib import Path
import statistics

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
RUNS = {
    'AlphaRAD': ROOT / 'experiments/supervised_baseline_classification/runs/20261120',
    'RadZero': ROOT / 'experiments/radzero_supervised_classification/runs/20261120',
}
DATASETS = {'openi': 'OpenI', 'chexpert': 'CheXpert', 'chestxray14': 'ChestXray14'}
METHODS = ('original', 'linear_probe', 'clip_global', 'post_mlp', 'pre_mlp')


def read_csv(path):
    with path.open(newline='') as stream:
        return list(csv.DictReader(stream))


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    rows, seeds, sources, protocols = [], [], {}, []
    for model, run in RUNS.items():
        assert json.loads((run / 'audit.json').read_text())['status'] == 'passed'
        assert json.loads((run / 'COMPLETION.json').read_text())['status'] == 'complete'
        protocols.append(json.loads((run / 'PROTOCOL.json').read_text()))
        for name in ('audit.json', 'COMPLETION.json', 'PROTOCOL.json', 'supervised_comparison.csv', 'all_runs.csv'):
            sources[str((run / name).relative_to(ROOT))] = digest(run / name)
        rows.extend(r for r in read_csv(run / 'supervised_comparison.csv')
                    if r['model'] == model and r['method'] in METHODS)
        seeds.extend(r for r in read_csv(run / 'all_runs.csv')
                     if r['model'] == model and r['method'] in METHODS)
    assert len(rows) == 30 and len(seeds) == 78
    assert protocols[0]['datasets'] == protocols[1]['datasets']
    assert protocols[0]['train'] == protocols[1]['train']
    for row in rows:
        fitted = sorted((s for s in seeds if all(s[k] == row[k] for k in ('model', 'dataset', 'method'))),
                        key=lambda s: int(s['seed']))
        assert [int(s['seed']) for s in fitted] == ([42] if row['method'] == 'original' else [42, 43, 44])
        classes = len(protocols[0]['datasets'][row['dataset']]['classes'])
        expected = (0 if row['method'] == 'original' else 769 * classes if row['method'] == 'linear_probe'
                    else 294912 if row['method'] == 'clip_global' else 99136)
        assert int(row['parameters']) == expected
        assert all(int(s['parameters']) == expected for s in fitted)
        for metric in ('auroc', 'ap'):
            values = [float(s[metric + '_percent']) for s in fitted]
            assert math.isclose(float(row[metric + '_mean']), statistics.mean(values), abs_tol=1e-8)
            if len(values) > 1:
                assert math.isclose(float(row[metric + '_std']), statistics.stdev(values), abs_tol=1e-8)
    content = [
        '% Generated by scripts/build_token_mlp_supervised_table.py; do not hand-edit.',
        r'\begin{table*}[!t]', r'\centering', r'\small',
        r'\setlength{\tabcolsep}{3pt}', r'\renewcommand{\arraystretch}{1.15}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llccccc@{}}', r'\toprule',
        r'Model & Dataset & Original & Linear probe & Global adapter$^{\dagger}$ & Post MLP & Pre MLP \\',
        r'\midrule',
    ]
    for model in RUNS:
        if model == 'RadZero':
            content.append(r'\midrule')
        for i, (dataset, label) in enumerate(DATASETS.items()):
            group = [next(r for r in rows if (r['model'], r['dataset'], r['method']) == (model, dataset, m)) for m in METHODS]
            best = {k: max(float(r[k]) for r in group) for k in ('auroc_mean', 'ap_mean')}
            cells = []
            for row in group:
                pair = []
                for k in best:
                    value = f"{float(row[k]):.2f}"
                    pair.append(r'\mathbf{' + value + '}' if value == f'{best[k]:.2f}' else value)
                cells.append('$' + r'\,/\,'.join(pair) + '$')
            model_cell = rf'\multirow{{{len(DATASETS)}}}{{*}}{{{model}}}' if i == 0 else ''
            content.append(' & '.join([model_cell, label, *cells]) + r' \\')
    content += [r'\bottomrule', r'\end{tabular*}',
        r'\caption{Supervised baselines for AlphaRAD and RadZero on the same local splits. Cells show macro AUROC / AP (\%); fitted methods report the mean over seeds 42/43/44, and Original is evaluated once. Bold marks the highest displayed value for each metric within a row, including ties; it does not indicate statistical significance. Pre/Post each use 99,136 trainable parameters, the global adapter uses 294,912, and the linear probe uses $769C$ (13,842/9,228/10,766 for OpenI/CheXpert/ChestXray14). $^{\dagger}$The global adapter is a CLIP-Adapter-style multilabel implementation on aligned CLS features with frozen model-specific scoring, not an exact reproduction of the original CLIP-Adapter experiment. All fitted methods share the supervision and training/validation budget; global-feature comparisons also change the aggregation path.}',
        r'\label{tab:token_mlp_supervised_baselines}', r'\end{table*}', '']
    target = PAPER / 'tables/token_mlp_supervised_baselines.tex'
    target.write_text('\n'.join(content))
    data = PAPER / 'supplement_data/token_mlp_supervised_baselines.csv'
    with data.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)
    provenance = dict(status='verified', scope='AlphaRAD and RadZero; three source datasets; five displayed methods. No external results included.',
        source_sha256=sources, summary_rows=30, underlying_evaluations=78, additional_fits_beyond_previous_manuscript=45,
        checks=['means and sample SDs recomputed from all seeds', 'shared datasets and training protocol', 'parameter counts', 'completed source audits'],
        table_sha256=digest(target), csv_sha256=digest(data), exporter_sha256=digest(Path(__file__)))
    (PAPER / 'supplement_data/token_mlp_supervised_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Exported 6 table rows; checked 30 method summaries against 78 saved evaluations.')


if __name__ == '__main__':
    main()

#!/usr/bin/env python3
"""Tabulate the actual cohorts and split memberships used throughout the paper."""
import csv
import hashlib
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
ROOT = PAPER.parent
SPLITS = ('train', 'val', 'test')


def digest(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def summarize(rows, identity):
    assert rows and len({r['id'] for r in rows}) == len(rows)
    for field in (identity, 'group_id'):
        membership = {}
        for row in rows:
            assert row['split'] in SPLITS
            assert membership.setdefault(str(row[field]), row['split']) == row['split'], field
    result = dict(total_images=len(rows), total_units=len({str(r[identity]) for r in rows}))
    for split in SPLITS:
        part = [r for r in rows if r['split'] == split]
        result[split + '_images'] = len(part)
        result[split + '_units'] = len({str(r[identity]) for r in part})
    assert sum(result[s + '_images'] for s in SPLITS) == result['total_images']
    assert sum(result[s + '_units'] for s in SPLITS) == result['total_units']
    return result


def main():
    sources = {}

    def record(path):
        path = Path(path)
        sources[str(path.relative_to(ROOT))] = digest(path)
        return read(path)

    primary_path = PAPER / 'supplement_data/token_mlp_results_provenance.json'
    primary = record(primary_path)
    assert primary['status'] == 'verified'
    rows, manifests = [], {}
    for key, name in [('openi', 'OpenI'), ('chexpert', 'CheXpert'), ('chestxray14', 'ChestXray14')]:
        spec = primary['datasets'][key]
        path = Path(spec['path'])
        assert digest(path) == spec['sha256']
        meta = record(path)
        assert digest(meta['samples_file']) == meta['samples_sha256'] == spec['samples_sha256']
        samples = record(meta['samples_file'])
        unit = 'uid' if key == 'openi' else 'patient_id'
        stats = summarize(samples, unit)
        for split in SPLITS:
            expected = meta['split_stats'][split]
            assert stats[split + '_images'] == expected['images']
            assert stats[split + '_units'] == expected['groups' if key == 'openi' else 'patients']
        rows.append(dict(setting='Primary', dataset=name, labels=len(meta['class_names']),
                         unit='reports' if key == 'openi' else 'patients', **stats))
        manifests[key] = samples
    large_run = ROOT / 'experiments/large_patient_multilabel/runs/20261121'
    large_protocol = record(large_run / 'PROTOCOL.json')
    meta = record(large_protocol['dataset'])
    assert digest(large_protocol['dataset']) == large_protocol['dataset_sha256']
    assert digest(meta['samples_file']) == meta['samples_sha256']
    samples = record(meta['samples_file'])
    stats = summarize(samples, 'patient_id')
    for split in SPLITS:
        assert stats[split + '_images'] == meta['split_stats'][split]['images']
        assert stats[split + '_units'] == meta['split_stats'][split]['patients']
    assert {r['id'] for r in samples} == {r['id'] for r in manifests['chestxray14']}
    rows.append(dict(setting='Larger NIH', dataset='ChestXray14', labels=len(meta['class_names']), unit='patients', **stats))
    transfer_run = ROOT / 'experiments/nih_chexpert_transfer/runs/20261121'
    transfer = record(transfer_run / 'PROTOCOL.json')
    sample_path = transfer_run / 'samples.json'
    assert digest(sample_path) == transfer['artifact_sha256'][str(sample_path)]
    samples = record(sample_path)
    assert all(r['split'] == 'test' for r in samples)
    assert {r['image'] for r in samples} == {r['image'] for r in manifests['chexpert']}
    stats = summarize(samples, 'patient_id')
    assert (stats['total_images'], stats['total_units']) == (transfer['images'], transfer['patients'])
    rows.append(dict(setting='Transfer target', dataset='CheXpert', labels=len(transfer['class_names']), unit='patients', **stats))
    lines = [r'% Generated by scripts/build_token_mlp_dataset_splits.py; do not hand-edit.',
        r'\begin{table*}[!t]', r'\centering', r'\footnotesize', r'\setlength{\tabcolsep}{3pt}',
        r'\renewcommand{\arraystretch}{1.15}',
        r'\begin{tabular*}{\textwidth}{@{\extracolsep{\fill}}llcrrrr@{}}', r'\toprule',
        r'Setting & Dataset & Labels & Total & Train & Validation & Test \\', r'\midrule']
    for index, row in enumerate(rows):
        if index in (3, 4):
            lines.append(r'\midrule')
        name = row['dataset'] + (r'$^{\dagger}$' if row['unit'] == 'reports' else '')
        counts = []
        for part in ('total', *SPLITS):
            n, units = row[part + '_images'], row[part + '_units']
            counts.append(f'{n:,} ({units:,})' if n else '---')
        lines.append(' & '.join([row['setting'], name, str(row['labels']), *counts]) + r' \\')
    lines += [r'\bottomrule', r'\end{tabular*}',
        r'\caption{Datasets and exact fixed splits used in this paper. Counts are images (patients), except $^{\dagger}$OpenI, where parentheses count reports and longitudinal patient independence is unverified. Primary splits are shared by all seven backbones and their applicable controls; the larger NIH and transfer settings evaluate AlphaRAD and RadZero. Group-based target ratios are 80/10/10 for primary splits and 60/10/30 for the larger NIH split; image proportions can differ because group sizes vary. Report/patient groups and exact duplicates remain within one partition. Transfer uses checkpoints fitted on the larger NIH training partition (13,406 images) and selected on its validation partition (2,300 images), then tests all 668 CheXpert images on seven shared labels; dashes indicate no CheXpert training or validation in that experiment. NIH rows reuse the same cohort, as do CheXpert rows, so their totals are not additive. These are local cohorts and splits, not complete datasets or official benchmark protocols.}',
        r'\label{tab:token_mlp_dataset_splits}', r'\end{table*}', '']
    target = PAPER / 'tables/token_mlp_dataset_splits.tex'
    target.write_text('\n'.join(lines))
    csv_path = PAPER / 'supplement_data/token_mlp_dataset_splits.csv'
    with csv_path.open('w', newline='') as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    provenance = dict(status='verified', rows=5, input_sha256=sources,
        counting='Image counts plus unique report UIDs for OpenI or patient IDs for the other datasets.',
        source_and_target_cohort_reuse_verified=True, table_sha256=digest(target),
        csv_sha256=digest(csv_path), exporter_sha256=digest(Path(__file__)))
    (PAPER / 'supplement_data/token_mlp_dataset_splits_provenance.json').write_text(json.dumps(provenance, indent=2) + '\n')
    print('Exported five settings; counts recomputed from image-level manifests and checked against saved protocols.')


if __name__ == '__main__':
    main()
